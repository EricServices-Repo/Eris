function subscribe<T>(channel: string, cb: (data: T) => void): () => void {
  const listener = (_event: IpcRendererEvent, data: T) => cb(data)
  ipcRenderer.on(channel, listener)
  return () => ipcRenderer.removeListener(channel, listener)
}

